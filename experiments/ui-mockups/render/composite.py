"""
composite.py - Pillow post-processing of the render passes + data export for the HTML overlays.

  m1: focus level (L8) at full contrast; the levels below fade darker/desaturated over 3 levels (z-mask pass);
      ghost massing of the structure above composited on top (ghost-only pass).
  thumbnails: section strip thumbnail (from the M2 section) used on the level-navigation screen.
  data.js: every camera json + anchors.json as JS globals, so overlays project world points exactly.
"""
import json, os, glob
import numpy as np
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out')
SRC = os.path.normpath(os.path.join(HERE, '..', 'src'))
IMG = os.path.join(SRC, 'img')
os.makedirs(IMG, exist_ok=True)


def rgb_to_hsv_arr(a):
    im = Image.fromarray(a.astype('uint8'), 'RGB').convert('HSV')
    return np.array(im).astype(float)


def m1():
    beauty = np.array(Image.open(os.path.join(OUT, 'm1_beauty.png')).convert('RGB')).astype(float)
    mask = np.array(Image.open(os.path.join(OUT, 'm1_zmask.png')).convert('RGBA')).astype(float) / 255.0
    ghost = Image.open(os.path.join(OUT, 'm1_ghost.png')).convert('RGBA')
    geo = mask[..., 3]
    focus = mask[..., 0]
    dim = geo * (1.0 - focus)                      # 0 at/above the focus level, -> 1 three levels below
    # value/saturation shift only (hue stays free to carry meaning): darker, greyer, a touch cooler
    grey = beauty.mean(axis=2, keepdims=True)
    desat = beauty + (grey - beauty) * (0.55 * dim[..., None])
    darker = desat * (1.0 - 0.36 * dim[..., None])
    cool = np.array([112.0, 121.0, 132.0])
    out = darker + (cool - darker) * (0.10 * dim[..., None])
    img = Image.fromarray(out.clip(0, 255).astype('uint8'), 'RGB').convert('RGBA')
    img.alpha_composite(ghost)
    img.convert('RGB').save(os.path.join(IMG, 'm1_bg.png'))


def section_thumb():
    """Crop of the M2 section around the building, scaled for the level-navigation inset."""
    im = Image.open(os.path.join(OUT, 'm2_section.png')).convert('RGB')
    box = (475, 170, 1355, 1370)               # render px (x0, y0, x1, y1) - building incl. undercroft
    s = 0.36
    th = im.crop(box).resize((round((box[2] - box[0]) * s), round((box[3] - box[1]) * s)), Image.LANCZOS)
    th.save(os.path.join(IMG, 'sec_thumb.png'))
    return dict(box=box, s=s, size=th.size)


def data_js(extra):
    cams = {}
    for f in sorted(glob.glob(os.path.join(OUT, '*.cam.json'))):
        cams[os.path.basename(f)[:-9]] = json.load(open(f))
    anchors = json.load(open(os.path.join(OUT, 'anchors.json')))
    with open(os.path.join(SRC, 'js', 'data.js'), 'w') as fh:
        fh.write('// generated by render/composite.py - camera + anchor data for the overlays\n')
        fh.write('window.CAMS = %s;\n' % json.dumps(cams))
        fh.write('window.ANCHORS = %s;\n' % json.dumps(anchors))
        fh.write('window.EXTRA = %s;\n' % json.dumps(extra))
        fh.write('window.LEVELS = %s;\n' % json.dumps(json.load(open(os.path.join(OUT, 'levels.json')))))


if __name__ == '__main__':
    m1()
    extra = dict(sec_thumb=section_thumb())
    data_js(extra)
    print('composited m1_bg, sec_thumb; wrote src/js/data.js')
